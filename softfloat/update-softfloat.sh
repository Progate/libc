#!/bin/sh
#
# Copies the parts of Berkeley SoftFloat that fenv-raise.c uses into
# berkeley-softfloat-3/, and regenerates names.h.
#
# names.h renames every external symbol of these files into the reserved
# namespace (f64_add -> __softfloat_f64_add, softfloat_roundPackToF64 ->
# __softfloat_roundPackToF64). Programs and libraries may carry their own copy
# of SoftFloat, built with other options, and must not bind to this one.
#
# Usage: CC="clang --target=wasm32-wasip1" NM=llvm-nm ./update-softfloat.sh

set -e

SOFTFLOAT_DIR="$(dirname "$(realpath "$0")")"
SOFTFLOAT_COMMIT=a0c6494cdc11865811dec815d5c0049fba9d82a8
SOFTFLOAT_TARBALL_URL="https://github.com/ucb-bar/berkeley-softfloat-3/archive/$SOFTFLOAT_COMMIT.tar.gz"
SOFTFLOAT_SRC_DIR="$SOFTFLOAT_DIR/berkeley-softfloat-3"
CC="${CC:-clang --target=wasm32-wasip1}"
NM="${NM:-llvm-nm}"

# The operations of fenv-raise.c and what they call, with the 8086-SSE
# specialization (tininess detected after rounding, as on x86).
SOURCES="
bf16_to_f32.c
f128_add.c f128_div.c f128_mul.c f128_sqrt.c f128_sub.c
f128_to_f16.c f128_to_f32.c f128_to_f64.c
f16_add.c f16_div.c f16_mul.c f16_sqrt.c f16_sub.c
f32_add.c f32_div.c f32_mul.c f32_sqrt.c f32_sub.c
f32_to_bf16.c f32_to_f16.c
f64_add.c f64_div.c f64_mul.c f64_sqrt.c f64_sub.c
f64_to_f16.c f64_to_f32.c
s_addMagsF128.c s_addMagsF16.c s_addMagsF32.c s_addMagsF64.c
s_approxRecipSqrt32_1.c s_approxRecipSqrt_1Ks.c
s_normRoundPackToF128.c s_normRoundPackToF32.c s_normRoundPackToF64.c
s_normSubnormalF128Sig.c s_normSubnormalF16Sig.c s_normSubnormalF32Sig.c
s_normSubnormalF64Sig.c
s_roundPackToBF16.c s_roundPackToF128.c s_roundPackToF16.c
s_roundPackToF32.c s_roundPackToF64.c
s_shiftRightJam128.c s_shiftRightJam128Extra.c
s_subMagsF128.c s_subMagsF16.c s_subMagsF32.c s_subMagsF64.c
softfloat_state.c
include/internals.h include/opts-GCC.h include/primitiveTypes.h
include/primitives.h include/softfloat.h include/softfloat_types.h
8086-SSE/s_bf16UIToCommonNaN.c 8086-SSE/s_commonNaNToBF16UI.c
8086-SSE/s_commonNaNToF16UI.c 8086-SSE/s_commonNaNToF32UI.c
8086-SSE/s_commonNaNToF64UI.c 8086-SSE/s_f128UIToCommonNaN.c
8086-SSE/s_f32UIToCommonNaN.c 8086-SSE/s_f64UIToCommonNaN.c
8086-SSE/s_propagateNaNF128UI.c 8086-SSE/s_propagateNaNF16UI.c
8086-SSE/s_propagateNaNF32UI.c 8086-SSE/s_propagateNaNF64UI.c
8086-SSE/softfloat_raiseFlags.c 8086-SSE/specialize.h
"

rm -rf "$SOFTFLOAT_SRC_DIR"
mkdir -p "$SOFTFLOAT_SRC_DIR"

echo "Downloading Berkeley SoftFloat $SOFTFLOAT_COMMIT"
members="berkeley-softfloat-3-$SOFTFLOAT_COMMIT/COPYING.txt"
for source in $SOURCES; do
    members="$members berkeley-softfloat-3-$SOFTFLOAT_COMMIT/source/$source"
done
# shellcheck disable=SC2086
curl -L "$SOFTFLOAT_TARBALL_URL" | tar xzf - --strip-components=1 -C "$SOFTFLOAT_SRC_DIR" $members

echo "Generating names.h"
objects="$(mktemp -d)"
for source in $SOURCES; do
    case "$source" in
    *.c)
        $CC -O2 -c -o "$objects/$(basename "$source" .c).o" \
            -DSOFTFLOAT_FAST_INT64 -DINLINE_LEVEL=5 \
            -DSOFTFLOAT_FAST_DIV32TO16 -DSOFTFLOAT_FAST_DIV64TO32 \
            -I"$SOFTFLOAT_DIR" -I"$SOFTFLOAT_SRC_DIR/source/include" \
            -I"$SOFTFLOAT_SRC_DIR/source/8086-SSE" \
            "$SOFTFLOAT_SRC_DIR/source/$source"
        ;;
    esac
done
symbols="$($NM --defined-only --extern-only --format=just-symbols "$objects"/*.o |
    grep -v ':$' | grep -v '^$' | sort -u)"
rm -rf "$objects"

# A primitive that a platform may provide as a macro is declared and defined
# under `#ifndef softfloat_<name>`, so it cannot be renamed with a macro. These
# get an asm label on a declaration that comes before SoftFloat's own.
guarded_prototypes='
softfloat_approxRecipSqrt32_1|uint32_t softfloat_approxRecipSqrt32_1(unsigned int oddExpA, uint32_t a)
softfloat_shiftRightJam128|struct uint128 softfloat_shiftRightJam128(uint64_t a64, uint64_t a0, uint_fast32_t dist)
softfloat_shiftRightJam128Extra|struct uint128_extra softfloat_shiftRightJam128Extra(uint64_t a64, uint64_t a0, uint64_t extra, uint_fast32_t dist)
'
{
    echo "/* Generated by update-softfloat.sh. Do not edit. */"
    echo "#include \"platform.h\""
    echo "#include \"primitiveTypes.h\""
    for symbol in $symbols; do
        if grep -q "^#ifndef $symbol\$" "$SOFTFLOAT_SRC_DIR/source/include/primitives.h"; then
            prototype="$(echo "$guarded_prototypes" | sed -n "s/^$symbol|//p")"
            if [ -z "$prototype" ]; then
                echo "update-softfloat.sh: no prototype for $symbol" >&2
                exit 1
            fi
            echo "$prototype __asm__(\"__$symbol\");"
        else
            case "$symbol" in
            softfloat_*) echo "#define $symbol __$symbol" ;;
            *) echo "#define $symbol __softfloat_$symbol" ;;
            esac
        fi
    done
} > "$SOFTFLOAT_DIR/names.h"

cat <<NOTICE > "$SOFTFLOAT_SRC_DIR/NOTICE.wasi-libc.md"
This directory contains a part of Berkeley SoftFloat Release 3e, licensed
under BSD-3-Clause. See COPYING.txt for the full license text.

The original source code can be found at $SOFTFLOAT_TARBALL_URL

## How to update Berkeley SoftFloat sources

1. Update the \`SOFTFLOAT_COMMIT\` variable in \`update-softfloat.sh\`
2. Run \`update-softfloat.sh\`
NOTICE
